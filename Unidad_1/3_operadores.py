#Operadores relacionales
a=10
b=5
#Menor que (<)
resultado=a<b
print(resultado)
#Mayor que (>)
resultado=a>b
print(resultado)
#Diferente que (!=)
resultado=a!=b
print(resultado)
#Igual que (==)
resultado=a==b
print(resultado)
#Menor o igual que (<=)
resultado=a<=b
#Mayor o igual que (>=)
resultado=a>=b
#OPERADORES LOGICOS
